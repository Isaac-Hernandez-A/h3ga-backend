-- Catálogos base referenciados por clientes, documentos y etapas. Solo estructura (sin datos).

CREATE TABLE regimen_principal (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL
);

CREATE TABLE ley_probable (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL
);

CREATE TABLE afore (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL
);

CREATE TABLE tipo_documento (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE etapas_proceso (
  id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_paso SMALLINT NOT NULL UNIQUE,
  nombre      TEXT NOT NULL
);

-- id sin autoincremento: el diccionario fija los ids 1 a 9.
CREATE TABLE estatus_tramite (
  id                     SMALLINT PRIMARY KEY,
  nombre                 TEXT NOT NULL,
  descripcion            TEXT NOT NULL,
  categoria              categoria_tramite NOT NULL,
  avance_porcentaje_fijo SMALLINT,
  avance_editable        BOOLEAN NOT NULL,
  avance_min             SMALLINT,
  avance_max             SMALLINT
);
