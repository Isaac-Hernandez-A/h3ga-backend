-- Etapa 0 (Diagnóstico Inicial) y correcciones F2.

CREATE TABLE historial_laboral (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  cliente_id        UUID NOT NULL UNIQUE REFERENCES clientes (id),
  semanas_issste    INTEGER NOT NULL,
  salario_promedio  NUMERIC(10, 2) NOT NULL,
  ultimo_patron     TEXT NOT NULL,
  vigencia_derechos estado_confirmacion NOT NULL,
  activo            BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE informacion_issste (
  id                   UUID PRIMARY KEY,
  historial_laboral_id UUID NOT NULL UNIQUE REFERENCES historial_laboral (id),
  nss_issste           VARCHAR(20) NOT NULL,
  regimen_pensionario  TEXT NOT NULL,
  anios_laborados      NUMERIC(5, 2),
  activo               BOOLEAN NOT NULL
);

CREATE TABLE tipo_correccion (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL
);

CREATE TABLE correcciones_cliente (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  cliente_id         UUID NOT NULL REFERENCES clientes (id),
  tipo_correccion_id SMALLINT NOT NULL REFERENCES tipo_correccion (id),
  observaciones      TEXT,
  tiempo_promedio    TEXT,
  dato_actual        TEXT,
  dato_correcto      TEXT
);

CREATE TABLE unificacion_nss_detalle (
  id                         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  correccion_id              UUID NOT NULL UNIQUE REFERENCES correcciones_cliente (id),
  nss_principal_elegido      VARCHAR(11) NOT NULL,
  criterio_seleccion         criterio_seleccion_nss NOT NULL,
  etapa_institucional_actual etapa_institucional_nss NOT NULL
);

CREATE TABLE unificacion_nss_secundarios (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  unificacion_id UUID NOT NULL REFERENCES unificacion_nss_detalle (id),
  nss            VARCHAR(11) NOT NULL,
  observaciones  TEXT
);

CREATE TABLE objetivo_especifico_inicial (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE cliente_objetivos_especificos (
  cliente_id  UUID NOT NULL REFERENCES clientes (id),
  objetivo_id SMALLINT NOT NULL REFERENCES objetivo_especifico_inicial (id),
  PRIMARY KEY (cliente_id, objetivo_id)
);
