-- Usuarios y roles (RBAC).

CREATE TABLE roles (
  id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      TEXT NOT NULL,
  descripcion TEXT
);

-- tipos_asesor pertenece a otro módulo (otro estudiante). Aquí solo se crea, vacía y sin datos,
-- para poder apuntar usuarios.tipo_asesor_id. Sus valores los define su dueño.
CREATE TABLE IF NOT EXISTS tipos_asesor (
  id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(50) NOT NULL UNIQUE,
  descripcion TEXT,
  activo      BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE usuarios (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  rol_id             SMALLINT NOT NULL REFERENCES roles (id),
  tipo_asesor_id     SMALLINT REFERENCES tipos_asesor (id),
  nombre             TEXT NOT NULL,
  apellido_paterno   TEXT NOT NULL,
  apellido_materno   TEXT NOT NULL,
  correo_electronico TEXT NOT NULL UNIQUE,
  contrasena_hash    VARCHAR(255) NOT NULL,
  activo             BOOLEAN NOT NULL DEFAULT true,
  fecha_creacion     TIMESTAMPTZ NOT NULL
);

COMMENT ON COLUMN usuarios.contrasena_hash IS 'Hash de la contraseña; nunca texto plano.';
