-- Etapa 1 (Diagnóstico Especializado) y sus catálogos, puentes y análisis.
-- modalidad10_criterios, modalidad40_criterios y retroactivo_evaluacion_conveniencia: el diccionario
-- indica "UUID (PK)" sin default, por eso su id no tiene DEFAULT.

CREATE TABLE diagnostico_especializado (
  id                                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  cliente_id                         UUID NOT NULL UNIQUE REFERENCES clientes (id),
  fecha_analisis                     DATE NOT NULL DEFAULT CURRENT_DATE,
  asesor_id                          UUID NOT NULL REFERENCES usuarios (id),
  fecha_primera_cotizacion           DATE,
  cotizo_antes_julio_1997            BOOLEAN NOT NULL,
  tipo_pension_probable              tipo_pension NOT NULL,
  edad_objetivo_pension              SMALLINT NOT NULL,
  comentarios_cliente                TEXT,
  observaciones_regimen              TEXT,
  fecha_ultima_baja                  DATE,
  ultimo_salario_cotizado            NUMERIC(10, 2),
  fecha_vencimiento_conservacion     DATE,
  tiene_conservacion_derechos        validacion_estado NOT NULL,
  tiempo_estimado_conservacion_meses INTEGER,
  dentro_de_conservacion             validacion_estado NOT NULL,
  requiere_reactivacion              BOOLEAN NOT NULL DEFAULT false,
  conviene_pensionar_ahora           conveniencia_pension NOT NULL,
  comentarios_conservacion           TEXT,
  semanas_reconocidas_al_baja        INTEGER,
  semanas_descontadas                INTEGER NOT NULL DEFAULT 0,
  semanas_reintegradas               INTEGER NOT NULL DEFAULT 0,
  semanas_efectivas_pension          INTEGER NOT NULL,
  semanas_requeridas_pension         INTEGER,
  trabaja_cuenta_propia              si_no_parcial NOT NULL,
  actividad_economica                TEXT,
  ingreso_mensual_aproximado         NUMERIC(10, 2),
  conclusion_modalidad_10            evaluacion_modalidad NOT NULL,
  comentarios_modalidad_10           TEXT,
  dado_de_baja_regimen_obligatorio   validacion_estado NOT NULL,
  conclusion_modalidad_40            evaluacion_modalidad NOT NULL,
  salario_propuesto_m40              NUMERIC(10, 2),
  meses_propuestos_m40               SMALLINT,
  evalua_retroactivo_m40             BOOLEAN NOT NULL DEFAULT false,
  comentarios_modalidad_40           TEXT,
  justificacion_estrategia           TEXT NOT NULL,
  siguiente_paso_sugerido            TEXT,
  conclusion_financiera              TEXT,
  firma_cliente_path                 TEXT,
  firma_asesor_path                  TEXT,
  fecha_firma                        TIMESTAMPTZ,
  creado_en                          TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en                     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Catálogos y puentes de estrategias, objetivos e inconsistencias.

CREATE TABLE estrategia_recomendada_tipo (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE diagnostico_estrategias_recomendadas (
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  estrategia_id  SMALLINT NOT NULL REFERENCES estrategia_recomendada_tipo (id),
  detalle_otro   TEXT,
  PRIMARY KEY (diagnostico_id, estrategia_id)
);

CREATE TABLE objetivo_diagnostico (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE diagnostico_objetivos (
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  objetivo_id    SMALLINT NOT NULL REFERENCES objetivo_diagnostico (id),
  detalle_otro   TEXT,
  PRIMARY KEY (diagnostico_id, objetivo_id)
);

CREATE TABLE tipo_inconsistencia_detectada (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE diagnostico_inconsistencias_generales (
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  tipo_id        SMALLINT NOT NULL REFERENCES tipo_inconsistencia_detectada (id),
  detalle_otro   TEXT,
  PRIMARY KEY (diagnostico_id, tipo_id)
);

-- Recuperación de semanas.

CREATE TABLE analisis_recuperacion_semanas (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  diagnostico_id UUID NOT NULL UNIQUE REFERENCES diagnostico_especializado (id),
  aplica         aplicabilidad_recuperacion NOT NULL,
  observaciones  TEXT
);

CREATE TABLE tipo_gestion_recuperacion (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE recuperacion_gestiones (
  analisis_id     UUID NOT NULL REFERENCES analisis_recuperacion_semanas (id),
  tipo_gestion_id SMALLINT NOT NULL REFERENCES tipo_gestion_recuperacion (id),
  detalle_otro    TEXT,
  PRIMARY KEY (analisis_id, tipo_gestion_id)
);

CREATE TABLE tipo_evidencia_recuperacion (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE recuperacion_evidencias (
  analisis_id       UUID NOT NULL REFERENCES analisis_recuperacion_semanas (id),
  tipo_evidencia_id SMALLINT NOT NULL REFERENCES tipo_evidencia_recuperacion (id),
  detalle_otro      TEXT,
  PRIMARY KEY (analisis_id, tipo_evidencia_id)
);

-- Modalidad 10.

-- id sin autoincremento: así lo indica el diccionario ("SMALLINT (PK)").
CREATE TABLE objetivo_modalidad_10 (
  id     SMALLINT PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE diagnostico_objetivos_m10 (
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  objetivo_id    SMALLINT NOT NULL REFERENCES objetivo_modalidad_10 (id),
  detalle_otro   TEXT,
  PRIMARY KEY (diagnostico_id, objetivo_id)
);

CREATE TABLE modalidad10_criterios (
  id             UUID PRIMARY KEY,
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  criterio       TEXT NOT NULL,
  cumple         BOOLEAN,
  observaciones  TEXT
);

-- Modalidad 40.

CREATE TABLE objetivo_modalidad_40 (
  id     SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE
);

CREATE TABLE diagnostico_objetivos_m40 (
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  objetivo_id    SMALLINT NOT NULL REFERENCES objetivo_modalidad_40 (id),
  detalle_otro   TEXT,
  PRIMARY KEY (diagnostico_id, objetivo_id)
);

CREATE TABLE modalidad40_criterios (
  id             UUID PRIMARY KEY,
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  criterio       TEXT NOT NULL,
  cumplimiento   cumplimiento_criterio NOT NULL,
  observaciones  TEXT
);

CREATE TABLE analisis_modalidad40_retroactivo (
  id                                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  diagnostico_id                     UUID NOT NULL UNIQUE REFERENCES diagnostico_especializado (id),
  fecha_propuesta_inicio_m40         DATE,
  fecha_solicitud                    DATE,
  meses_retroactivos_estimados       SMALLINT,
  salario_diario_propuesto           NUMERIC(10, 2),
  cuotas_estimadas                   NUMERIC(12, 2),
  recargos_actualizaciones_estimadas NUMERIC(12, 2),
  total_estimado_pagar               NUMERIC(12, 2),
  baja_por_mora_previa               BOOLEAN,
  dentro_de_plazo_reingreso          validacion_estado NOT NULL,
  conclusion_retroactivo             evaluacion_retroactivo NOT NULL,
  comentarios                        TEXT
);

CREATE TABLE retroactivo_evaluacion_conveniencia (
  id             UUID PRIMARY KEY,
  retroactivo_id UUID NOT NULL REFERENCES analisis_modalidad40_retroactivo (id),
  pregunta       TEXT NOT NULL,
  respuesta      BOOLEAN
);

-- Escenarios, periodos, plan de acción y situación patrimonial.

CREATE TABLE escenario_pension (
  id                           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  diagnostico_f1_id            UUID NOT NULL REFERENCES diagnostico_especializado (id),
  nombre_escenario             TEXT NOT NULL,
  orden                        SMALLINT NOT NULL,
  semanas_proyectadas          INTEGER NOT NULL,
  salario_promedio_proyectado  NUMERIC(10, 2) NOT NULL,
  inversion_total_estimada     NUMERIC(12, 2) NOT NULL DEFAULT 0,
  pension_mensual_estimada     NUMERIC(12, 2) NOT NULL,
  incremento_mensual           NUMERIC(12, 2) NOT NULL,
  meses_recuperacion_inversion NUMERIC(6, 1),
  beneficio_a_5_anios          NUMERIC(12, 2),
  beneficio_a_10_anios         NUMERIC(12, 2),
  beneficio_a_15_anios         NUMERIC(12, 2),
  salario_modalidad_40         NUMERIC(10, 2),
  meses_modalidad_40           SMALLINT,
  costo_mensual_estimado       NUMERIC(12, 2)
);

CREATE TABLE periodos_inconsistencias (
  id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  cliente_id           UUID NOT NULL REFERENCES clientes (id),
  nombre_patron        TEXT NOT NULL,
  periodo_reclamado    TEXT NOT NULL,
  semanas_esperadas    INTEGER NOT NULL,
  semanas_reconocidas  INTEGER NOT NULL DEFAULT 0,
  evidencia_disponible TEXT NOT NULL,
  accion_sugerida      TEXT NOT NULL,
  estatus              estatus_inconsistencia NOT NULL DEFAULT 'pendiente'
);

CREATE TABLE plan_accion (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  diagnostico_id UUID NOT NULL REFERENCES diagnostico_especializado (id),
  accion         TEXT NOT NULL,
  fecha_objetivo DATE,
  estatus        estatus_plan_accion NOT NULL,
  observaciones  TEXT
);

CREATE TABLE situacion_patrimonial (
  id                              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  diagnostico_f1_id               UUID NOT NULL UNIQUE REFERENCES diagnostico_especializado (id),
  saldo_cuenta_individual         NUMERIC(12, 2) NOT NULL,
  aportaciones_voluntarias        NUMERIC(12, 2) NOT NULL,
  ahorros_inversiones_adicionales NUMERIC(12, 2) NOT NULL,
  bienes_patrimoniales            TEXT NOT NULL,
  creditos_deudas_vigentes        TEXT NOT NULL,
  ingreso_mensual                 NUMERIC(12, 2) NOT NULL,
  otras_fuentes_ingreso           TEXT NOT NULL,
  ingreso_conyuge                 NUMERIC(12, 2) NOT NULL,
  seguros                         TEXT NOT NULL,
  estado_salud                    estado_salud NOT NULL,
  padecimientos                   TEXT NOT NULL,
  estado_civil                    estado_civil NOT NULL,
  edad_conyuge                    SMALLINT,
  actividad_economica_conyuge     TEXT
);

CREATE TABLE situacion_patrimonial_hijos (
  id                       UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  situacion_patrimonial_id UUID NOT NULL REFERENCES situacion_patrimonial (id),
  numero_hijos             SMALLINT NOT NULL DEFAULT 0,
  tiene_discapacidad       BOOLEAN NOT NULL DEFAULT false,
  edad                     SMALLINT NOT NULL
);
